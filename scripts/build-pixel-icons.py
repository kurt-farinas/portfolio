out = {}
for name, rows in ICONS.items():
    assert len(rows) == 16, (name, len(rows))
    rects = []
    for y, row in enumerate(rows):
        assert len(row) == 16, (name, y, len(row), row)
        x = 0
        while x < 16:
            ch = row[x]
            if ch == '.':
                x += 1; continue
            start = x
            while x < 16 and row[x] == ch: x += 1
            rects.append([start, y, x - start, ch])
    out[name] = rects

js = "// Generated by scripts/build-pixel-icons.py from 16x16 character maps; edit the maps there, not this file.\n"
js += "// Each rect is [x, y, width, paletteLetter]; letters map to --pix-<letter> CSS variables.\n"
js += "export const PIXEL_ICONS = " + json.dumps(out, separators=(',', ':')) + ";\n"
pathlib.Path('src/components/desktop/pixelIcons.js').write_text(js, encoding='utf-8', newline='\n')
print('icons', len(out), 'bytes', len(js))
