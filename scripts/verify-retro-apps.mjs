import { chromium, expect } from '@playwright/test';
import fs from 'node:fs/promises';
const base = process.env.PORTFOLIO_PREVIEW_URL || 'http://127.0.0.1:4176';
const output = 'test-results/portfolio-ui';
await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch();
try {
  for (const theme of ['dark','light']) {
    const context = await browser.newContext({viewport:{width:375,height:812}});
    await context.addInitScript(theme => localStorage.setItem('portfolio-theme',theme),theme);
    const page = await context.newPage();
    const scenes = []; page.on('request',r=>{if(/DeskScene/.test(r.url())) scenes.push(r.url());});
    await page.goto(base+'/');
    await expect(page.locator('.retro-boot')).toBeVisible();
    await expect(page.getByRole('button',{name:'Sound: Off'})).toBeVisible();
    await page.screenshot({path:output+'/375-'+theme+'-boot.png'});
    await page.getByRole('button',{name:'Enter desktop',exact:true}).click();
    await expect(page.locator('.retro-boot')).not.toBeVisible();
    await page.goto(base+'/#terminal');
    const input=page.getByRole('textbox',{name:'Portfolio command'});
    await input.fill('<img src=x onerror=alert(1)>');await input.press('Enter');
    await expect(page.locator('.retro-terminal-output')).toContainText('<img src=x onerror=alert(1)>');
    await expect(page.locator('.retro-terminal-output img')).toHaveCount(0);
    await input.fill('education');await input.press('Enter');
    await expect(page.locator('.retro-terminal-output')).toContainText('STI College San Jose');
    await expect(page.locator('.retro-terminal-output')).not.toContainText('CLSU');
    await page.goto(base+'/#kurtordle');
    await page.getByRole('textbox',{name:'Five-letter guess'}).fill('REACT');
    await page.getByRole('textbox',{name:'Five-letter guess'}).press('Enter');
    await expect(page.locator('.retro-game-message')).toContainText('Solved: REACT');
    await page.getByRole('button',{name:'Minimize KurtOrdle window'}).click();
    await page.getByRole('button',{name:'Restore KurtOrdle',exact:true}).click();
    await expect(page.locator('.retro-game-message')).toContainText('Solved: REACT');
    await page.screenshot({path:output+'/375-'+theme+'-kurtordle.png'});
    await page.goto(base+'/#bughunter');
    const arena=page.locator('.retro-bug-arena canvas');
    await arena.focus();await page.keyboard.press('Space');
    await expect(page.locator('[data-app-scroll="bughunter"]')).toContainText('Bugs squashed: 1');
    await page.getByRole('button',{name:'Open app search'}).click();
    await expect(arena).toHaveAttribute('data-game-active','false');
    await page.keyboard.press('Escape');await expect(arena).toHaveAttribute('data-game-active','true');
    await page.getByRole('button',{name:'Minimize BugHunter 3D window'}).click();
    await expect(arena).toHaveCount(0);
    await page.getByRole('button',{name:'Restore BugHunter 3D',exact:true}).click();
    await expect(page.locator('[data-app-scroll="bughunter"]')).toContainText('Bugs squashed: 1');
    await page.screenshot({path:output+'/375-'+theme+'-bughunter.png'});
    await page.goto(base+'/#contact');
    let calls=0;
    await page.route('https://api.web3forms.com/submit',route=>{
      calls++;
      return route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(calls===1?{success:false,message:'Mock failure. Please retry.'}:{success:true})});
    });
    await page.getByRole('textbox',{name:'Your name',exact:true}).fill('QA Recruiter');
    await page.getByRole('textbox',{name:'Your email',exact:true}).fill('qa@example.com');
    await page.getByRole('textbox',{name:'Message',exact:true}).fill('Mock submission only.');
    await page.getByRole('button',{name:'Send message',exact:true}).click();
    await expect(page.locator('.retro-mail-status')).toContainText('Mock failure');
    await expect(page.getByRole('textbox',{name:'Your name',exact:true})).toHaveValue('QA Recruiter');
    await page.getByRole('button',{name:'Send message',exact:true}).click();
    await expect(page.locator('.retro-mail-status')).toContainText('Message sent');
    await expect(page.getByRole('textbox',{name:'Your name',exact:true})).toHaveValue('');
    expect(calls).toBe(2);
    await page.getByRole('button',{name:'Open application list'}).click();
    await page.getByRole('button',{name:'Turn monitor off',exact:true}).click();
    await expect(page.getByRole('button',{name:'Power on monitor'})).toBeVisible();
    await page.getByRole('button',{name:'Power on monitor'}).click();
    await page.getByRole('button',{name:'Open application list'}).click();
    await page.getByRole('button',{name:'Replay boot',exact:true}).click();
    await page.getByRole('button',{name:'Enter desktop',exact:true}).click();
    await expect(page.locator('.desktop-window.is-active')).toHaveAttribute('data-app-id','contact');
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    expect(scenes).toEqual([]);
    await context.close();
  }
  const failed=await browser.newContext({viewport:{width:1440,height:900}});
  await failed.addInitScript(()=>sessionStorage.setItem('kurt-os-boot-seen','true'));
  const page=await failed.newPage();await page.route('**/DeskScene-*.js',route=>route.abort());
  await page.goto(base+'/');
  await expect(page.locator('.desktop-fallback-note')).toBeVisible();
  await expect(page.locator('.desktop-window.is-active')).toHaveAttribute('data-app-id','about');
  await failed.close();
  const lost = await browser.newContext({viewport:{width:1440,height:900}});
  await lost.addInitScript(()=>sessionStorage.setItem('kurt-os-boot-seen','true'));
  const lostPage = await lost.newPage();await lostPage.goto(base+'/');
  await lostPage.locator('.desk-canvas canvas').waitFor();
  await lostPage.locator('.desk-projection-frame').waitFor({timeout:20000});
  await lostPage.locator('.desk-canvas canvas').evaluate(canvas=>canvas.dispatchEvent(new Event('webglcontextlost',{cancelable:true})));
  await expect(lostPage.locator('.desktop-fallback-note')).toBeVisible();
  await lost.close();
  console.log('Retro extras verified in both phone themes: boot, terminal escaping, games/restoration/modal pause, mocked contact feedback, power, replay, and 3D chunk failure recovery.');
} finally {await browser.close();}
